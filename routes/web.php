<?php

use Illuminate\Support\Facades\Route;
use App\Http\Controllers\CookieController;

/*
|--------------------------------------------------------------------------
| Web Routes
|--------------------------------------------------------------------------
*/

Route::get('/', function () {
    return view('welcome');
})->name('home');

/*
|--------------------------------------------------------------------------
| Cookie Consent Routes
|--------------------------------------------------------------------------
*/

Route::prefix('cookie')->name('cookie.')->group(function () {

    /*
    |--------------------------------------------------------------------------
    | Consent Page
    |--------------------------------------------------------------------------
    */
    Route::get('/consent', [
        CookieController::class,
        'consent'
    ])->name('consent');

    /*
    |--------------------------------------------------------------------------
    | Accept / Reject
    |--------------------------------------------------------------------------
    */
    Route::post('/accept', [
        CookieController::class,
        'accept'
    ])->name('accept');

    /*
    |--------------------------------------------------------------------------
    | Update Preferences
    |--------------------------------------------------------------------------
    */
    Route::post('/update', [
        CookieController::class,
        'update'
    ])->name('update');

    /*
    |--------------------------------------------------------------------------
    | Revoke Consent
    |--------------------------------------------------------------------------
    */
    Route::post('/revoke', [
        CookieController::class,
        'revoke'
    ])->name('revoke');

    /*
    |--------------------------------------------------------------------------
    | Cookie Policy
    |--------------------------------------------------------------------------
    */
    Route::get('/policy', [
        CookieController::class,
        'policy'
    ])->name('policy');

    /*
    |--------------------------------------------------------------------------
    | Consent History
    |--------------------------------------------------------------------------
    */
    Route::get('/history', [
        CookieController::class,
        'history'
    ])->name('history');

    /*
    |--------------------------------------------------------------------------
    | Export Consent History
    |--------------------------------------------------------------------------
    */
    Route::get('/history/export', [
        CookieController::class,
        'exportHistory'
    ])->name('history.export');
});

/*
|--------------------------------------------------------------------------
| Protected Route
|--------------------------------------------------------------------------
*/

Route::get('/dashboard', function () {
    return view('dashboard');
})
    ->middleware('cookie.consent')
    ->name('dashboard');
